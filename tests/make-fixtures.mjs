/** row = [num, prio, name, dur, bStart, bFin, aStart, aFin, sp, cppH, cppE, pyH, pyE, netH, netE, frH, frE] */
function writeWorkbook(name, rows) {
  const aoa = [HEADER, ...rows];
  const ws = XLSX.utils.aoa_to_sheet(aoa, { cellDates: true });
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Задачи');
  XLSX.writeFile(wb, join(outDir, name), { cellDates: true });
  console.log('wrote', name);
}

